export function toFirstPersonEpistemicBoundary(
  assessment:
    SelfBoundaryAssessment,
): FirstPersonEpistemicBoundary {
  return Object.freeze({
    experienceId:
      assessment.experienceId,

    firstPersonOwnershipAllowed:
      assessment
        .mayTreatAsOwnMentalState,

    /*
     * External information may affect cognition.
     *
     * Sovereignty does NOT mean isolation from the world.
     */
    influenceAllowed:
      assessment
        .integrity
        .entityValid &&
      assessment
        .integrity
        .clockValid &&
      assessment
        .integrity
        .provenancePresent,

    provenanceRequired:
      true as const,

    canonicalMutationAllowed:
      false as const,
  });
}

