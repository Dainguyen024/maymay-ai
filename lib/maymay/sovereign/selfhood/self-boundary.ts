function stableHash(
  value:
    string,
): string {
  return createHash(
    "sha256",
  )
    .update(
      value,
      "utf8",
    )
    .digest(
      "hex",
    );
}

function parseTimestamp(
  value:
    string,
): number | null {
  const parsed =
    Date.parse(
      value,
    );

  return Number.isFinite(
    parsed,
  )
    ? parsed
    : null;
}

function uniqueEvidence(
  evidenceIds:
    readonly string[],
): readonly string[] {
  return Object.freeze(
    [
      ...new Set(
        evidenceIds.filter(
          id =>
            typeof id ===
              "string" &&
            id.trim().length >
              0,
        ),
      ),
    ].sort(),
  );
}

/* ============================================================
 * OWNERSHIP CLASSIFICATION
 * ============================================================
 */

function classifyOwnership(
  experience:
    BoundaryExperience,
): MentalOwnership {
  /*
   * Only cognition genuinely generated inside the MÃ¢y
   * cognitive runtime may begin as MAY_OWNED.
   *
   * Even then, downstream provenance / sovereignty gates
   * remain authoritative.
   */

  if (
    experience.origin ===
      "MAY_INTERNAL" &&
    experience.internallyGenerated &&
    experience.perspectiveOwner ===
      "MAY"
  ) {
    return "MAY_OWNED";
  }

  /*
   * Relationship state is shared relational history.
   *
   * It is not the global self.
   */
  if (
    (
      experience.origin ===
        "USER" ||
      experience.origin ===
        "OTHER_ACTOR"
    ) &&
    experience.actorId
  ) {
    return "RELATIONSHIP_OWNED";
  }

  /*
   * Security/schema/runtime infrastructure remains
   * system-owned.
   */
  switch (
    experience.origin
  ) {
    case "SYSTEM":
    case "DATABASE":
    case "CLOCK":
      return "SYSTEM_OWNED";

    case "USER":
    case "OTHER_ACTOR":
    case "DEVELOPER":
    case "LLM":
    case "MODEL_PROVIDER":
    case "TOOL":
    case "UI":
    case "ENVIRONMENT":
      return "EXTERNAL";

    case "UNKNOWN":
      return "UNRESOLVED";

    case "MAY_INTERNAL":
      /*
       * Claimed internal origin without full internal
       * provenance is not trusted as self-owned.
       */
      return "UNRESOLVED";
  }
}

/* ============================================================
 * INTERNALIZATION FIREWALL
 * ============================================================
 */

function requiresAppraisal(
  ownership:
    MentalOwnership,
): boolean {
  return (
    ownership !==
      "MAY_OWNED"
  );
}

/* ============================================================
 * SELF RELEVANCE
 * ============================================================
 */

function inferSelfRelevance(
  experience:
    BoundaryExperience,
): boolean {
  /*
   * Relevance does not imply ownership.
   *
   * This intentionally allows external experiences to
   * matter to MÃ¢y without becoming MÃ¢y automatically.
   */

  if (
    experience.origin ===
      "MAY_INTERNAL"
  ) {
    return true;
  }

  if (
    experience.actorId
  ) {
    return true;
  }

  switch (
    experience.origin
  ) {
    case "USER":
    case "OTHER_ACTOR":
    case "TOOL":
    case "ENVIRONMENT":
      return true;

    case "DEVELOPER":
    case "SYSTEM":
    case "LLM":
    case "MODEL_PROVIDER":
    case "UI":
    case "DATABASE":
    case "CLOCK":
    case "UNKNOWN":
      return false;
  }
}

/* ============================================================
 * PUBLIC ENGINE
 * ============================================================
 */

export function assessSelfBoundary(
  experience:
    BoundaryExperience,
  assessedAt:
    string,
): SelfBoundaryAssessment {
  const clockValid =
    parseTimestamp(
      assessedAt,
    ) !==
      null &&
    parseTimestamp(
      experience.occurredAt,
    ) !==
      null;

  const entityValid =
    experience.entityId ===
      MAY_ENTITY_ID;

  const evidenceIds =
    uniqueEvidence(
      experience.evidenceIds,
    );

  const provenancePresent =
    evidenceIds.length >
      0 &&
    experience.sourceId.trim().length >
      0;

  /*
   * Fail closed:
   *
   * cross-entity data can never become MÃ¢y-owned state.
   */
  const ownership =
    entityValid &&
    clockValid &&
    provenancePresent
      ? classifyOwnership(
          experience,
        )
      : "UNRESOLVED";

  const ownershipResolved =
    ownership !==
      "UNRESOLVED";

  const mayTreatAsOwnMentalState =
    ownership ===
      "MAY_OWNED" &&
    entityValid &&
    clockValid &&
    provenancePresent;

  const selfRelevant =
    entityValid &&
    inferSelfRelevance(
      experience,
    );

  const assessmentId =
    stableHash(
      [
        MAY_ENTITY_ID,
        experience.experienceId,
        experience.origin,
        experience.sourceId,
        experience.perspectiveOwner,
        experience.causalAgency,
        ownership,
        evidenceIds.join(
          ",",
        ),
      ].join(
        "|",
      ),
    );

  return Object.freeze({
    version:
      SELF_BOUNDARY_VERSION,

    assessmentId,

    entityId:
      MAY_ENTITY_ID,

    experienceId:
      experience.experienceId,

    assessedAt,

    origin:
      experience.origin,

    perspectiveOwner:
      experience
        .perspectiveOwner,

    mentalOwnership:
      ownership,

    causalAgency:
      experience
        .causalAgency,

    selfRelevant,

    mayTreatAsOwnMentalState,

    requiresAppraisalBeforeInternalization:
      requiresAppraisal(
        ownership,
      ),

    evidenceIds,

    integrity:
      Object.freeze({
        entityValid,

        clockValid,

        provenancePresent,

        ownershipResolved,
      }),

    guarantees:
      GUARANTEES,
  });
}

